-- 1-сабақ, 2-бөлім: «Оқу орталығы» дерекқорының толық схемасы.
-- ЕСКЕРТУ: қайта орындау кестелерді және бар деректерді өшіреді!
-- Тәуелділіктерге байланысты алдымен байланыстырушы кесте жойылады.
DROP TABLE IF EXISTS enrollments CASCADE;
DROP TABLE IF EXISTS courses CASCADE;
DROP TABLE IF EXISTS students CASCADE;
DROP TABLE IF EXISTS teachers CASCADE;

CREATE TABLE teachers (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(120) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    CONSTRAINT chk_teacher_name CHECK (LENGTH(TRIM(full_name)) > 0),
    CONSTRAINT chk_teacher_email CHECK (POSITION('@' IN email) > 1)
);

CREATE TABLE students (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(120) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    group_name  VARCHAR(30) NOT NULL,
    CONSTRAINT chk_student_name CHECK (LENGTH(TRIM(full_name)) > 0),
    CONSTRAINT chk_student_group CHECK (LENGTH(TRIM(group_name)) > 0),
    CONSTRAINT chk_student_email CHECK (POSITION('@' IN email) > 1)
);

CREATE TABLE courses (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(160) NOT NULL,
    description TEXT,
    hours       INTEGER NOT NULL,
    teacher_id  INTEGER NOT NULL,
    CONSTRAINT chk_course_title CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT chk_course_hours CHECK (hours > 0),
    CONSTRAINT fk_courses_teacher FOREIGN KEY (teacher_id)
        REFERENCES teachers(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE enrollments (
    student_id  INTEGER NOT NULL,
    course_id   INTEGER NOT NULL,
    enrolled_at DATE NOT NULL DEFAULT CURRENT_DATE,
    grade       SMALLINT,
    CONSTRAINT pk_enrollments PRIMARY KEY (student_id, course_id),
    CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id)
        REFERENCES students(id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_enrollment_course FOREIGN KEY (course_id)
        REFERENCES courses(id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT chk_enrollment_grade CHECK (grade BETWEEN 0 AND 100)
);
